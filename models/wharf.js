    var pileX = [-0.92, 0.92], pileZ = [-1.26, -1.78];
    var a, b;
    for (a = 0; a < 2; a++) {
      for (b = 0; b < 2; b++) {
        tube(0.09, 0.11, 0.64, 7, M_WOOD, pileX[a], -1.20, pileZ[b]);
        tube(0.12, 0.12, 0.04, 7, M_DARK, pileX[a], -0.88, pileZ[b]);
      }
    }
    /* 水中独立系船桩 */
    tube(0.07, 0.09, 0.92, 7, M_WOOD, 1.62, -0.94, -0.62);
    tube(0.06, 0.08, 0.82, 7, M_WOOD, -1.60, -1.00, -0.95);
    tube(0.10, 0.10, 0.05, 7, M_DARK, 1.62, -0.50, -0.62);

    /* ---- 5. 系船石 + 缆绳 ---- */
    tube(0.10, 0.14, 0.36, 8, M_DARK, -1.02, -0.62, -1.78);
    tube(0.10, 0.14, 0.36, 8, M_DARK, 1.02, -0.62, -1.78);
    tube(0.13, 0.13, 0.04, 8, M_STONE, -1.02, -0.44, -1.78);
    tube(0.13, 0.13, 0.04, 8, M_STONE, 1.02, -0.44, -1.78);

    rod(1.02, -0.44, -1.78, 1.12, -0.55, -1.86, 0.024, M_WOOD);
    rod(1.12, -0.55, -1.86, 1.22, -0.68, -1.90, 0.024, M_WOOD);
    rod(1.22, -0.68, -1.90, 1.30, -0.83, -1.88, 0.022, M_WOOD);
    rod(1.30, -0.83, -1.88, 1.34, -0.98, -1.84, 0.022, M_WOOD);

    /* 平台上的缆绳圈 */
    ring(-0.86, -0.775, -1.66, 0.11, 0.022, 0.20);
    ring(-0.72, -0.772, -1.55, 0.10, 0.020, -0.30);
    ring(-0.98, -0.778, -1.52, 0.09, 0.020, 0.60);

    /* ---- 6. 水线湿石 ---- */
    slab(3.46, 0.10, 0.05, M_WET, 3, 0.4, 0, -0.88, 0.305);
    slab(2.72, 0.10, 0.05, M_WET, 2.2, 0.4, 0, -0.87, -1.925);
    slab(0.05, 0.10, 0.84, M_WET, 0.4, 0.4, -1.375, -0.87, -1.52);
    slab(0.05, 0.10, 0.84, M_WET, 0.4, 0.4, 1.375, -0.87, -1.52);

    /* ---- 7. 岸上两侧矮石墙 ---- */
    var sx, side = [-1.56, 1.56], wc, wk;
    for (a = 0; a < 2; a++) {
      sx = side[a];
      for (wc = 0; wc < 4; wc++) {
        for (wk = 0; wk < 3; wk++) {
          slab(0.22, 0.26, 0.23, M_DARK, 0.4, 0.5,
            sx + rng.range(-0.012, 0.012), 0.14 + wc * 0.26, 0.44 + wk * 0.24);
        }
      }
      slab(0.30, 0.08, 0.80, M_STONE, 0.6, 0.4, sx, 1.09, 0.68);
      tube(0.10, 0.12, 1.14, 7, M_STONE, sx, 0.57, 0.32);
      tube(0.09, 0.11, 1.10, 7, M_STONE, sx, 0.55, 1.04);
      tube(0.13, 0.13, 0.05, 7, M_DARK, sx, 1.14, 0.32);
      tube(0.12, 0.12, 0.05, 7, M_DARK, sx, 1.11, 1.04);
    }

    /* ---- 8. 岸边石板铺地 ---- */
    var gx, gz;
    for (gx = 0; gx < 4; gx++) {
      for (gz = 0; gz < 4; gz++) {
        slab(0.44, 0.04, 0.24, M_STONE, 0.5, 0.3,
          -0.72 + gx * 0.48, 0.02, 0.36 + gz * 0.22,
          0, rng.range(-0.04, 0.04), 0);
      }
    }
    slab(1.10, 0.03, 0.26, M_DARK, 0.9, 0.3, -0.60, 0.04, 1.18, 0, 0.10, 0);

    /* ---- 9. 墙根陶罐 / 木盆 / 竹篮 ---- */
    jar(0.16, 0.34, -1.24, 0.40, M_DARK);
    jar(0.13, 0.27, -1.22, 0.72, M_DARK);
    jar(0.17, 0.36, 1.26, 0.46, M_DARK);
    jar(0.12, 0.24, 1.24, 0.76, M_DARK);
    jar(0.14, 0.29, 1.20, 0.18, M_STONE);
    jar(0.11, 0.21, -1.20, 0.20, M_STONE);

    tube(0.24, 0.18, 0.18, 10, M_WOOD, 0.30, 0.13, 0.62);
    tube(0.20, 0.20, 0.02, 10, M_WET, 0.30, 0.205, 0.62);
    tube(0.18, 0.14, 0.22, 8, M_BAMBOO, -0.40, 0.15, 0.62);
    slab(0.16, 0.08, 0.16, M_CW, 0.5, 0.5, -0.40, 0.20, 0.62, 0, 0.3, 0);
    tube(0.10, 0.085, 0.15, 8, M_WOOD, 0.66, 0.11, 0.70);
    tube(0.085, 0.085, 0.02, 8, M_WET, 0.66, 0.19, 0.70);

    /* ---- 10. 晾衣架 ---- */
    tube(0.035, 0.045, 1.62, 6, M_WOOD, -0.72, 0.84, 0.86);
    tube(0.035, 0.045, 1.62, 6, M_WOOD, 0.72, 0.84, 0.86);
    tube(0.03, 0.03, 1.56, 6, M_BAMBOO, 0, 1.60, 0.86, 0, 0, Math.PI / 2);
    /* 斜撑 */
    rod(-0.72, 1.42, 0.86, -0.94, 0.02, 0.90, 0.026, M_BAMBOO);
    rod(0.72, 1.42, 0.86, 0.94, 0.02, 0.90, 0.026, M_BAMBOO);

    cloth(0.40, 0.66, M_CW, -0.44, 1.27, 0.87, 0.06);
    cloth(0.50, 0.78, M_CI, 0.00, 1.21, 0.87, -0.04);
    cloth(0.34, 0.56, M_CW, 0.42, 1.32, 0.87, 0.10);
    /* 盆中待洗的衣物 */
    cloth(0.16, 0.20, M_CW, 0.30, 0.20, 0.62, 0.5);

    /* ---- 11. 斜置洗衣石 + 水洼 ---- */
    slab(0.52, 0.12, 0.40, M_DARK, 0.6, 0.5, 0.86, 0.09, 0.42);
    slab(0.54, 0.08, 0.42, M_STONE, 0.6, 0.5, 0.86, 0.18, 0.42, -0.16);
    tube(0.20, 0.20, 0.02, 12, M_WET, 0.55, 0.045, 0.34);
    tube(0.13, 0.13, 0.02, 12, M_WET, 0.28, 0.045, 0.44);
    tube(0.09, 0.09, 0.02, 10, M_WET, -0.86, 0.045, 0.26);

    /* 竹篙斜靠在石墙 */
    rod(1.48, 0.10, 0.30, 1.30, 1.20, 0.88, 0.030, M_BAMBOO);
    rod(-1.46, 0.10, 1.10, -1.28, 1.16, 0.62, 0.028, M_BAMBOO);

    /* ---- 12. 石缝青苔 / 草丛 / 水中石 ---- */
    slab(0.30, 0.12, 0.03, M_LEAF, 0.3, 0.3, -1.60, -0.50, 0.315);
    slab(0.26, 0.10, 0.03, M_LEAF, 0.3, 0.3, 1.60, -0.72, 0.315);
    slab(0.22, 0.09, 0.03, M_LEAF, 0.3, 0.3, -1.58, -0.22, 0.315);
    slab(0.20, 0.09, 0.03, M_LEAF, 0.3, 0.3, 1.59, -0.36, 0.315);
    slab(0.44, 0.03, 0.26, M_LEAF, 0.4, 0.3, -0.62, -0.785, -1.38);
    slab(0.36, 0.03, 0.16, M_LEAF, 0.4, 0.2, 0.72, -0.315, -0.32);
    slab(0.30, 0.03, 0.14, M_LEAF, 0.3, 0.2, -0.70, -0.625, -0.82);
    slab(0.34, 0.05, 0.20, M_LEAF, 0.4, 0.2, -1.42, 0.05, 0.50);
    slab(0.26, 0.04, 0.14, M_LEAF, 0.3, 0.2, 1.44, 0.05, 0.42);
    slab(0.22, 0.03, 0.12, M_LEAF, 0.3, 0.2, 0.90, -0.40, -0.90);
    slab(0.18, 0.03, 0.10, M_LEAF, 0.3, 0.2, -1.00, -0.44, -1.06);
    slab(0.16, 0.03, 0.10, M_LEAF, 0.3, 0.2, 0.34, -0.68, -1.28);

    grass(6, 0.20, -1.38, 0.04, 0.44, 11);
    grass(7, 0.18, 1.40, 0.04, 0.62, 23);
    grass(5, 0.16, -1.52, -0.86, 0.20, 37);
    grass(5, 0.14, 1.54, -0.84, -0.05, 53);
    grass(4, 0.13, -0.86, 0.04, 1.02, 61);
    grass(4, 0.12, 1.10, 0.04, 0.98, 67);

    rock(0.12, 1.60, -0.95, 0.02, 71);
    rock(0.09, -1.64, -0.94, -0.30, 79);
    rock(0.10, 0.10, -0.96, 0.02, 87);
    rock(0.08, -0.30, -0.94, 0.06, 91);
    rock(0.07, 0.62, -0.93, -0.18, 97);

    slab(0.16, 0.10, 0.14, M_DARK, 0.2, 0.2, 0.95, 0.06, 0.24, 0, 0.3, 0);
    slab(0.12, 0.08, 0.12, M_DARK, 0.2, 0.2, -0.98, 0.05, 0.28, 0, -0.2, 0);
    slab(0.10, 0.07, 0.10, M_DARK, 0.2, 0.2, 0.22, 0.04, 1.12, 0, 0.5, 0);

