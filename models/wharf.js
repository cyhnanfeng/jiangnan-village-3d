      top = T0 - i * RISE;
      zc = Z0 - i * RUN;
      slab(SW, top + 1.20, 0.28, M_STONE, 2.4, 1.2, 0, (top - 1.20) / 2, zc);
      slab(SW, 0.05, 0.09, M_DARK, 2.4, 0.4, 0, top - 0.025, zc - 0.14);
